#!/usr/bin/env python3
"""Generate openair1/PHY/NR_UE_TRANSPORT/tests/nr_dci11_spec_fields.inc from the text of TS 38.212 clause 7.3.1.2.2 (Format 1_1).

usage: gen_dci11_spec_fields.py <38212-xxx.docx> <version label> > nr_dci11_spec_fields.inc
The docx is the 3GPP archive file (https://www.3gpp.org/ftp/Specs/archive/38_series/38.212/). Every field heading line of the clause
("-<TAB>Name - <widths> bits ...") becomes one entry {name, widths} in payload order; widths are the explicit numbers of the heading
and of its "-<TAB><digit> bits ..." sub-lines ("0, 1, 2, or 3 bits", "5 bits if ...; otherwise 4 bits", "6 bits if ...") -- every
"N bit(s)" number stated; empty when the width is a formula (e.g. the FDRA). Nothing is interpreted beyond that: the test compares this list with the resolver's switch table."""
import html, re, sys, zipfile

def text(path):
    x = zipfile.ZipFile(path).read('word/document.xml').decode('utf8')
    x = re.sub(r'</w:p>', '\n', x)
    x = re.sub(r'<w:tab/>', '\t', x)
    return html.unescape(re.sub(r'<[^>]+>', '', x))

t = text(sys.argv[1]).split('\n')
start = max(i for i, l in enumerate(t) if l.strip() == '7.3.1.2.2\tFormat 1_1')
end = next(i for i in range(start, len(t)) if t[i].startswith('Table 7.3.1.2.2-1'))
head = re.compile(r'^-\t([A-Z][A-Za-z0-9 _/()\-]*?) (?:–|-) (.*)$')
rows = []
num = re.compile(r'(\d+(?:, \d+)*(?:,? or \d+)?) bits?\b')
for l in t[start:end]:
    m = head.match(l)
    if m:
        rows.append([m.group(1).strip(), set(int(v) for g in num.findall(m.group(2)) for v in re.findall(r'\d+', g))])
    elif rows and re.match(r'^-\t\d', l):  # a "-<TAB>6 bits if ..." sub-line of the field above
        rows[-1][1] |= set(int(v) for g in num.findall(l) for v in re.findall(r'\d+', g))
rows = [(n, sorted(w)) for n, w in rows]
print('/* GENERATED by tools/dci11/gen_dci11_spec_fields.py from 3GPP TS 38.212 %s, clause 7.3.1.2.2 (Format 1_1): every field' % sys.argv[2])
print(' * heading in payload order with the widths the heading states (empty: the width is a formula). Do not edit by hand. */')
print('static const struct { const char *name; int n; int w[8]; } kSpec1_1[] = {')
for name, w in rows:
    print('  {"%s", %d, {%s}},' % (name, len(w), ', '.join(map(str, w))))
print('};')

GRID0 = -10
FLOOR_GUARD_DB = 1.0

def true_snr_db(est_db, qm):
    """Invert the DD-EVM bias; None when est is within 1 dB of the floor (unknown SNR, never qualified).
    shortcut: AWGN + ideal ZF only (no multi-layer noise enhancement), ~+-1.5 dB near the floor."""
    t = TRUE_TO_EST.get(qm)
    if t is None or est_db < t[0] + FLOOR_GUARD_DB:
        return None
    if est_db >= t[-1]:
        return est_db
    for i in range(len(t) - 1):
        if est_db <= t[i + 1]:
            d = t[i + 1] - t[i]
            return GRID0 + i + ((est_db - t[i]) / d if d > 0 else 0.0)

ANSI = re.compile(r'\x1b\[[0-9;]*m')
KV = re.compile(r'(\w+)=(\S+)')
RECOV = re.compile(r'RECOVLATE rnti=(\S+) (\d+\.\d+) .*?(?:tot_us=(-?\d+))?\s*$')
EVKEY = re.compile(r'EVMGRANT rnti=(\S+) (\d+\.\d+) ')

def required_snr_db(mcs, tbl):
    t = TABLES.get(tbl, T64)
    if mcs < 0 or mcs >= len(t):
        return None
    qm, r = t[mcs]
    return 10 * math.log10(2 ** (qm * r / 1024) - 1) + IMPL_LOSS_DB

def pct(v, p):
    if not v:
        return None
    s = sorted(v)
    return s[min(len(s) - 1, int(p * len(s)))]

def empty():
    return {'lat': [], 'crc_all': [0, 0], 'n_q': 0, 'ok_q': 0, 'low': 0, 'retx': 0, 'floor': 0, 'drops': None, 'skipped': 0}

def classify(acc, crc, mcs, tbl, rv, snr, margin, evm=True):
    # evm=False: UL snr_db is a DM-RS SNR, not the DL decision-directed EVM, so it is used as is
    req = required_snr_db(mcs, tbl) if rv == 0 else None
    if req is None:
        acc['retx'] += 1
        return
    ts = true_snr_db(snr, TABLES.get(tbl, T64)[mcs][0]) if evm else snr
    if ts is None:
        acc['floor'] += 1
    elif ts >= req + margin:
        acc['n_q'] += 1; acc['ok_q'] += crc
    else:
        acc['low'] += 1

def summary(acc):
    lat = acc['lat']; n = acc['crc_all'][1]
    return {'n_real': n, 'tot_p50': pct(lat, .5), 'tot_p99': pct(lat, .99), 'tot_p999': pct(lat, .999),
            'crc_all': 100.0 * acc['crc_all'][0] / n if n else None, 'n_q': acc['n_q'],
            'crc_q': 100.0 * acc['ok_q'] / acc['n_q'] if acc['n_q'] else None,
            'unqualified_low_snr': acc['low'], 'unqualified_retx': acc['retx'], 'unqualified_floor': acc['floor'],
            'drops_pct': acc['drops'], 'skipped': acc['skipped'], 'recovered': acc.get('recovered', 0),
            'recovered_tot_p99': pct(acc['rec_lat'], .99) if acc.get('rec_lat') else None}

def parse_run(path, margin=2.0, cell=None):
    dl, ul = empty(), empty()
    lines = cellsel.prepare(cellsel.read_lines(path), cell, path)
    # ISAC_PDSCH_RECOVERY_ASYNC logs EVMGRANT for the first pass (crc=0) and a RECOVLATE line when a retry arm rescues it later: credit it.
    rec = {m.group(1, 2): int(m.group(3)) if m.group(3) else -1 for m in (RECOV.search(r) for r in lines if 'RECOVLATE' in r) if m}
    dl['recovered'] = 0
    for raw in lines:
        if 'SENSING:' not in raw:
            continue
        line = ANSI.sub('', raw)
        kv = dict(KV.findall(line))
        try:
            if 'EVMGRANT' in line:
                if kv.get('probe', '0') != '0':
                    continue
                crc, mcs, tbl, nl, rv = (int(kv[k]) for k in ('crc', 'mcs', 'tbl', 'Nl', 'rv'))
                m = EVKEY.search(line)
                tot = int(kv['e2e'].split(',')[6])
                if not crc and m and m.groups() in rec:
                    crc = 1; dl['recovered'] += 1
                    if rec[m.groups()] >= 0:
                        tot = rec[m.groups()]; dl.setdefault('rec_lat', []).append(tot)
                snr = min(float(x) for x in kv['snr_l'].split(',')[:max(1, nl)])
                dl['lat'].append(tot); dl['crc_all'][0] += crc; dl['crc_all'][1] += 1
                classify(dl, crc, mcs, tbl, rv, snr, margin)
            elif 'UL_PUSCH_CRC' in line:
                if kv.get('probe', '0') != '0':
                    continue
                ok, mcs = int(kv['ok']), int(kv['mcs'])
                ul['crc_all'][0] += ok; ul['crc_all'][1] += 1
                classify(ul, ok, mcs, int(kv.get('tbl', 0)), 0, float(kv['snr_db']), margin, evm=False)
            elif 'UL_E2E' in line:
                if kv.get('probe', '0') != '0':
                    continue
                ul['lat'].append(int(kv['tot']))
            elif 'PDSCHQ queued=' in line:
                m = re.search(r'queued=(\d+).*full=(\d+) stale=(\d+).*dropped_narrow=(\d+)', line)
                q, f, s, n = map(int, m.groups())
                dl['drops'] = 100.0 * (f + s + n) / q if q else None
            elif 'PUSCHQ2' in line:
                m = re.search(r'real\[queued=(\d+) full=(\d+)\]', line)
                q, f = map(int, m.groups())
                st = re.search(r'real_stale=(\d+)', line)  # ULST ISAC_UL_STALE_DROP: stale real grants are drops too
                f += int(st.group(1)) if st else 0
                ul['drops'] = 100.0 * f / q if q else None
        except (KeyError, ValueError, IndexError, AttributeError):
            (dl if 'EVMGRANT' in line or 'PDSCHQ' in line else ul)['skipped'] += 1
    return {'dl': summary(dl), 'ul': summary(ul)}

def verdict(s):
    ok = (s['tot_p99'] is not None and s['tot_p99'] < 3000, s['crc_q'] is not None and s['crc_q'] >= 80,  # p99 < 3 ms (goal 2026-10-17)
          s['drops_pct'] is not None and s['drops_pct'] < 1)
    return 'PASS' if all(ok) else 'FAIL(' + ','.join(n for n, g in zip(('lat', 'crc', 'drops'), ok) if not g) + ')'

if __name__ == '__main__':
    args = sys.argv[1:]; margin = 2.0; as_json = False
    if '--margin' in args:
        i = args.index('--margin'); margin = float(args[i + 1]); del args[i:i + 2]
    if '--json' in args:
        args.remove('--json'); as_json = True
    def show(p, r):
        for d in ('dl', 'ul'):
            s = r[d]
            print(f"{p} {d.upper()} {verdict(s)} " + ' '.join(f"{k}={v:.1f}" if isinstance(v, float) else f"{k}={v}" for k, v in s.items()))
    for p in args:
        info = cellsel.cell_info(p)
        if info is None:
            r = parse_run(p, margin)
            if as_json:
                print(json.dumps({'run': p, **r}))
            else:
                show(p, r)
            continue
        rs = {k: parse_run(p, margin, k) for k in info['cells']}
        for k, r in rs.items():
            r['pci'] = info['pci'].get(k); r['counts'] = info['counts'][k]
        if as_json:
            print(json.dumps({'run': p, 'cells': {str(k): r for k, r in rs.items()}, 'untagged': info['untagged']}))
            continue
        for k, r in rs.items():
            print(cellsel.cell_header(k, info['pci'].get(k)))
            show(p, r)
            print(f"{p} CELL pci={r['pci']} {cellsel.counts_line(r['counts'])}")
        print(f"{p} UNTAGGED (process-wide, in no cell) {cellsel.counts_line(info['untagged'])}")
